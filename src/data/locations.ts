export const areaBySlug = (slug: string) => serviceAreas.find((a) => a.slug === slug);

export const tier1Areas = serviceAreas.filter((a) => a.tier === 1);

export const areasByRegion = (region: Borough) =>
  serviceAreas.filter((a) => a.region === region);

export const areaCount = serviceAreas.length;

/** Resolve nearby names to real area records (skips any that aren't listed). */
export const nearbyAreas = (area: ServiceArea) =>
  area.nearby
    .map((n) => serviceAreas.find((a) => a.name === n))
    .filter((a): a is ServiceArea => Boolean(a));
