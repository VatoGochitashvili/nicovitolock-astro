// tier 1 = core market. Gets its own area page AND a full /services/[slug]/[name]
//          page for every service (the programmatic-SEO surface).
// tier 2 = covered and listed everywhere, gets its own area page, but no full
//          service matrix. This is deliberate: 100 x 12 thin pages would get us
//          filtered as doorway content. Depth where it converts, coverage
//          everywhere else.

export type Borough = 'Brooklyn' | 'Staten Island';

export type AreaTrait =
  | 'rowhouse' | 'multifamily' | 'singlefamily' | 'waterfront'
  | 'commercial' | 'prewar' | 'industrial' | 'highrise' | 'gated';

export interface ServiceArea {
  slug: string;
  name: string;
  region: Borough;
  zip: string;
  tier: 1 | 2;
  /** Unique local copy — the anti-duplicate-content workhorse. */
  blurb: string;
  /** Real streets / landmarks, woven into page copy so no two pages match. */
  landmarks: string[];
  /** Neighboring areas, for interlinking + copy. */
  nearby: string[];
  /** Housing character — drives service-relevant local copy. */
  character: string;
  /** Derived housing traits. Each one unlocks a different block of
   *  service-relevant local copy, so no two neighborhoods read alike. */
  traits: AreaTrait[];
  /** Approx. drive time from our Bay Ridge base. */
  eta: string;
  /** [lat, lng] — an APPROXIMATE neighborhood centre, for plotting the
   *  coverage map only. These are not addresses and must never be presented
   *  as one: we are a mobile business with no premises. Being a block or two
   *  out is fine for a pin that says "we cover here". */
  coords: [number, number];
}

